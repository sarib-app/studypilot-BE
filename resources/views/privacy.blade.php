    <h1>StudyPilot Privacy Policy</h1>
    <p class="updated">Last updated: {{ now()->format('F j, Y') }}</p>

    <p>StudyPilot ("we", "us") is a study-planning and focus-timer app. This page explains what
    information we collect, why, and how you can remove it.</p>

    <h2>Information we collect</h2>
    <ul>
        <li><strong>Account information:</strong> name, email address, and date of birth (used only to confirm you're 13 or older).</li>
        <li><strong>Sign-in information:</strong> if you use Google or Apple Sign-In, we receive a unique identifier and, where you allow it, your name and email from that provider. We never see your Google or Apple password.</li>
        <li><strong>Study preferences:</strong> grade/year, curriculum, city, subjects you choose to study, and your weekly study goal.</li>
        <li><strong>Study activity:</strong> the sessions you plan or complete, including subject, duration, timestamps, and any optional reflection you add after a session.</li>
        <li><strong>Notification preferences:</strong> your chosen reminder timing settings.</li>
    </ul>

    <h2>How we use it</h2>
    <p>Solely to run the app for you: signing you in, remembering your subjects and goals, showing
    your plan and progress, calculating your study streak, and sending the reminders you've asked for.
    We do not sell your data, and we do not use it for advertising.</p>

    <h2>Third parties</h2>
    <p>We use Google Sign-In and Apple Sign-In only to verify your identity when you choose to sign
    in that way. We don't share your data with any other third party.</p>

    <h2>Children's privacy</h2>
    <p>StudyPilot is not intended for children under 13. We ask for your date of birth at sign-up
    specifically to block accounts for anyone under that age.</p>

    <h2>Data retention and deletion</h2>
    <p>We keep your data for as long as your account is active. You can permanently delete your
    account and all associated data at any time from within the app (your profile → Delete Account),
    or by emailing us at the address below.</p>

